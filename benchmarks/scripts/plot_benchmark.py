import pandas as pd
import matplotlib.pyplot as plt
import argparse
import re
import sys



# Parse command line arguments for the benchmark CSV file
def parse_args():
    parser = argparse.ArgumentParser(description="Analyze Google Benchmark CSV and generate thesis charts.")
    parser.add_argument("csv_file", help="Path to the CSV file generated by the benchmark")
    return parser.parse_args()




# Extract the number of threads from csv file.
# Example: "BM_KernelSchedulerYield/real_time/threads:32_mean" -> 32
def extract_threads(name):
    match = re.search(r'threads:(\d+)', name)
    return int(match.group(1)) if match else 0




# read data from csv passed as an argument from terminal
# filter mean and stdDev from the csv
# extract number of threads with extract_threads(name) function
# merge df_mean and df_std dataframes on the key threads, producing items_per_second_mean/std to avoid confilct on the same var items_per_second
# items_per_second_mean is the number of sched_yield() cycle completed in a second
# dividing 1e9 (1 sec in nanosec) by this value I can get the round-trip for a sched_yield() cycle
def process_data(csv_file):
    try:
        df = pd.read_csv(csv_file)                                 
    except FileNotFoundError:
        print(f"Error: File {csv_file} not found.")
        sys.exit(1)
        
    df_mean = df[df['name'].str.endswith('_mean')].copy()
    df_std  = df[df['name'].str.endswith('_stddev')].copy()
    
    df_mean['threads'] = [extract_threads(name) for name in df_mean['name']] 
    df_std['threads']  = [extract_threads(name) for name in  df_std['name']] 
    
    data = pd.merge(df_mean[['threads', 'items_per_second']], 
                    df_std[['threads', 'items_per_second']], 
                    on='threads', 
                    suffixes=('_mean', '_std'))
    
    data['latency_ns'] = 1e9 / data['items_per_second_mean']
    
    return data




def plot_throughput(data):
    plt.figure(figsize=(10, 6))
    
    plt.errorbar(data['threads'], data['items_per_second_mean'], 
                 yerr=data['items_per_second_std'], 
                 fmt='-o', color='#d62728', capsize=5, capthick=1.5, markersize=6)
    
    plt.xscale('log', base=2)
    plt.title('Kernel CFS Scheduler: Throughput Degradation\n(Cost in Context Switches / Second)', fontsize=14, pad=15)
    plt.xlabel('Number of Concurrent Threads', fontsize=12)
    plt.ylabel('Throughput (Operations per second)', fontsize=12)
    plt.xticks(data['threads'], data['threads'])
    plt.grid(True, which="both", ls="--", alpha=0.6)
    
    plt.tight_layout()
    plt.savefig('throughput_chart.png', dpi=300)
    print("-> Created: throughput_chart.png")




def plot_latency(data):
    plt.figure(figsize=(10, 6))
    
    plt.plot(data['threads'], data['latency_ns'], '-o', color='#1f77b4', markersize=6)
    
    plt.xscale('log', base=2)
    plt.title('Kernel CFS Scheduler: Context Switch Latency\n(Cost of a single sched_yield)', fontsize=14, pad=15)
    plt.xlabel('Number of Concurrent Threads', fontsize=12)
    plt.ylabel('Latency (Nanoseconds)', fontsize=12)
    plt.xticks(data['threads'], data['threads'])
    plt.grid(True, which="both", ls="--", alpha=0.6)
    
    for i in [0, len(data)-1]:
        plt.annotate(f"{data['latency_ns'].iloc[i]:.0f} ns", 
                     (data['threads'].iloc[i], data['latency_ns'].iloc[i]), 
                     textcoords="offset points", xytext=(0,10), ha='center', 
                     fontsize=10, fontweight='bold')
                     
    plt.tight_layout()
    plt.savefig('latency_chart.png', dpi=300)
    print("-> Created: latency_chart.png")
    
   
    

def main():
    args = parse_args()
    
    data = process_data(args.csv_file)
    print("Data processed successfully. Generating charts...")
    
    
    plt.style.use('seaborn-v0_8-darkgrid')
    
    plot_throughput(data)
    plot_latency(data)
    
    
    
    

if __name__ == "__main__":
    main()
